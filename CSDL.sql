CREATE DATABASE PharmaDB

-- Sử dụng Database PharmaDB (Hãy chắc chắn bạn đã tạo DB này trước)
USE PharmaDB;
GO

-- 1. Bảng Loại Sản Phẩm
CREATE TABLE LOAISP (
    MALOAI NVARCHAR(20) NOT NULL PRIMARY KEY,
    TENLOAI NVARCHAR(100)
);

-- 2. Bảng Kho
CREATE TABLE KHO (
    MAKHO NVARCHAR(20) NOT NULL PRIMARY KEY,
    TENKHO NVARCHAR(100),
    DIACHI NVARCHAR(255)
);

-- 3. Bảng Nhà Cung Cấp
CREATE TABLE NHACUNGCAP (
    MANCC NVARCHAR(20) NOT NULL PRIMARY KEY,
    TENNCC NVARCHAR(100),
    SDT NVARCHAR(20),
    EMAIL NVARCHAR(100),
    DIACHI NVARCHAR(255)
);

-- 4. Bảng Khách Hàng
CREATE TABLE KHACHHANG (
    MAKH NVARCHAR(20) NOT NULL PRIMARY KEY,
    TENKH NVARCHAR(100),
    SDT NVARCHAR(20),
    DIACHI NVARCHAR(255),
    LOAIKH NVARCHAR(50)
);

-- 5. Bảng Nhân Viên
CREATE TABLE NHANVIEN (
    MANV NVARCHAR(20) NOT NULL PRIMARY KEY,
    TENNV NVARCHAR(100),
    GIOITINH NVARCHAR(10),
    CHUCVU NVARCHAR(50),
    EMAIL NVARCHAR(100),
    CCCD NVARCHAR(20),
    SDT NVARCHAR(20),
    DIACHI NVARCHAR(255),
    NGAYSINH DATE,
    TRANGTHAI INT DEFAULT 1,
    AVATAR VARBINARY(MAX) -- Chuyển từ BLOB sang VARBINARY(MAX)
);

-- 6. Bảng Tài Khoản (Phụ thuộc NHANVIEN)
CREATE TABLE TAIKHOAN (
    MANV NVARCHAR(20) NOT NULL PRIMARY KEY,
    MATKHAU NVARCHAR(100),
    QUYENHAN NVARCHAR(50),
    TRANGTHAI INT,
    CONSTRAINT FK_TAIKHOAN_NHANVIEN FOREIGN KEY (MANV) REFERENCES NHANVIEN(MANV)
);

-- 7. Bảng Sản Phẩm (Phụ thuộc LOAISP)
CREATE TABLE SANPHAM (
    MASP NVARCHAR(20) NOT NULL PRIMARY KEY,
    TENSP NVARCHAR(255),
    DVT NVARCHAR(50),
    GIABAN DECIMAL(18, 2), -- Dùng DECIMAL cho tiền tệ
    HOATCHAT NVARCHAR(255),
    NUOCSX NVARCHAR(100),
    MALOAI NVARCHAR(20),
    NHACUNGCAP NVARCHAR(100), -- Giữ nguyên cột này từ file cũ
    GHICHU NVARCHAR(MAX),
    CONSTRAINT FK_SANPHAM_LOAISP FOREIGN KEY (MALOAI) REFERENCES LOAISP(MALOAI)
);

-- 8. Bảng Lô Hàng (Phụ thuộc SANPHAM)
CREATE TABLE LOHANG (
    MALO NVARCHAR(20) NOT NULL PRIMARY KEY,
    MASP NVARCHAR(20),
    SOHIEU NVARCHAR(50),
    NSX DATE,
    HSD DATE,
    NHACUNGCAP NVARCHAR(100),
    CONSTRAINT FK_LOHANG_SANPHAM FOREIGN KEY (MASP) REFERENCES SANPHAM(MASP)
);

-- 9. Bảng Tồn Kho (Phụ thuộc KHO, SANPHAM, LOHANG)
CREATE TABLE TONKHO (
    MAKHO NVARCHAR(20) NOT NULL,
    MASP NVARCHAR(20) NOT NULL,
    MALO NVARCHAR(20) NOT NULL,
    SOLUONGTON INT DEFAULT 0,
    PRIMARY KEY (MAKHO, MASP, MALO),
    CONSTRAINT FK_TONKHO_KHO FOREIGN KEY (MAKHO) REFERENCES KHO(MAKHO),
    CONSTRAINT FK_TONKHO_SANPHAM FOREIGN KEY (MASP) REFERENCES SANPHAM(MASP),
    CONSTRAINT FK_TONKHO_LOHANG FOREIGN KEY (MALO) REFERENCES LOHANG(MALO)
);

-- 10. Bảng Hóa Đơn Nhập (Phụ thuộc NHANVIEN, NHACUNGCAP)
CREATE TABLE HOADONNHAP (
    SOHDNHAP NVARCHAR(20) NOT NULL PRIMARY KEY,
    NGAYLAP DATETIME DEFAULT GETDATE(),
    TONGTIEN DECIMAL(18, 2),
    MANV NVARCHAR(20),
    MANCC NVARCHAR(20),
    GHICHU NVARCHAR(MAX),
    TRANGTHAI NVARCHAR(50),
    CONSTRAINT FK_HDNHAP_NHANVIEN FOREIGN KEY (MANV) REFERENCES NHANVIEN(MANV),
    CONSTRAINT FK_HDNHAP_NCC FOREIGN KEY (MANCC) REFERENCES NHACUNGCAP(MANCC)
);

-- 11. Bảng Chi Tiết Hóa Đơn Nhập (Phụ thuộc HOADONNHAP, SANPHAM, LOHANG)
CREATE TABLE CTHDNHAP (
    SOHDNHAP NVARCHAR(20) NOT NULL,
    MASP NVARCHAR(20) NOT NULL,
    MALO NVARCHAR(20) NOT NULL,
    SOLUONG INT,
    DONGIANHAP DECIMAL(18, 2),
    THANHTIEN DECIMAL(18, 2),
    PRIMARY KEY (SOHDNHAP, MASP, MALO),
    CONSTRAINT FK_CTHDNHAP_HD FOREIGN KEY (SOHDNHAP) REFERENCES HOADONNHAP(SOHDNHAP),
    CONSTRAINT FK_CTHDNHAP_SP FOREIGN KEY (MASP) REFERENCES SANPHAM(MASP),
    CONSTRAINT FK_CTHDNHAP_LO FOREIGN KEY (MALO) REFERENCES LOHANG(MALO)
);

-- 12. Bảng Hóa Đơn Xuất (Phụ thuộc NHANVIEN, KHACHHANG)
-- Đã thêm cột TRANGTHAI_DUYET theo yêu cầu trước đó
CREATE TABLE HOADONXUAT (
    SOHDXUAT NVARCHAR(20) NOT NULL PRIMARY KEY,
    NGAYLAP DATETIME DEFAULT GETDATE(),
    TONGTIEN DECIMAL(18, 2),
    VAT FLOAT DEFAULT 0,
    MANV NVARCHAR(20),
    MAKH NVARCHAR(20),
    TRANGTHAI NVARCHAR(50),
    TRANGTHAI_DUYET INT DEFAULT 0, -- 0: Chờ duyệt, 1: Đã duyệt
    CONSTRAINT FK_HDXUAT_NHANVIEN FOREIGN KEY (MANV) REFERENCES NHANVIEN(MANV),
    CONSTRAINT FK_HDXUAT_KHACHHANG FOREIGN KEY (MAKH) REFERENCES KHACHHANG(MAKH)
);

-- 13. Bảng Chi Tiết Hóa Đơn Xuất (Phụ thuộc HOADONXUAT, SANPHAM, LOHANG)
CREATE TABLE CTHDXUAT (
    SOHDXUAT NVARCHAR(20) NOT NULL,
    MASP NVARCHAR(20) NOT NULL,
    MALO NVARCHAR(20) NOT NULL,
    SOLUONG INT,
    DONGIABAN DECIMAL(18, 2),
    THANHTIEN DECIMAL(18, 2),
    PRIMARY KEY (SOHDXUAT, MASP, MALO),
    CONSTRAINT FK_CTHDXUAT_HD FOREIGN KEY (SOHDXUAT) REFERENCES HOADONXUAT(SOHDXUAT),
    CONSTRAINT FK_CTHDXUAT_SP FOREIGN KEY (MASP) REFERENCES SANPHAM(MASP),
    CONSTRAINT FK_CTHDXUAT_LO FOREIGN KEY (MALO) REFERENCES LOHANG(MALO)
);

-- 14. Bảng Phiếu Nhập (Phụ thuộc HOADONNHAP, KHO, NHANVIEN)
CREATE TABLE PHIEUNHAP (
    MAPN NVARCHAR(20) NOT NULL PRIMARY KEY,
    SOHDNHAP NVARCHAR(20),
    MAKHO NVARCHAR(20),
    MANV NVARCHAR(20),
    NGAYNHAP DATETIME DEFAULT GETDATE(),
    GHICHU NVARCHAR(MAX),
    CONSTRAINT FK_PHIEUNHAP_HD FOREIGN KEY (SOHDNHAP) REFERENCES HOADONNHAP(SOHDNHAP),
    CONSTRAINT FK_PHIEUNHAP_KHO FOREIGN KEY (MAKHO) REFERENCES KHO(MAKHO),
    CONSTRAINT FK_PHIEUNHAP_NV FOREIGN KEY (MANV) REFERENCES NHANVIEN(MANV)
);

-- 15. Bảng Phiếu Xuất (Phụ thuộc HOADONXUAT, KHO, NHANVIEN)
CREATE TABLE PHIEUXUAT (
    MAPX NVARCHAR(20) NOT NULL PRIMARY KEY,
    SOHDXUAT NVARCHAR(20),
    MAKHO NVARCHAR(20),
    MANV NVARCHAR(20),
    NGAYXUAT DATETIME DEFAULT GETDATE(),
    LYDO NVARCHAR(MAX),
    CONSTRAINT FK_PHIEUXUAT_HD FOREIGN KEY (SOHDXUAT) REFERENCES HOADONXUAT(SOHDXUAT),
    CONSTRAINT FK_PHIEUXUAT_KHO FOREIGN KEY (MAKHO) REFERENCES KHO(MAKHO),
    CONSTRAINT FK_PHIEUXUAT_NV FOREIGN KEY (MANV) REFERENCES NHANVIEN(MANV)
);

-- 16. Bảng Thanh Toán (Phụ thuộc HOADONXUAT, NHANVIEN)
CREATE TABLE THANHTOAN (
    MATT NVARCHAR(20) NOT NULL PRIMARY KEY,
    SOHDXUAT NVARCHAR(20),
    SOTIEN DECIMAL(18, 2),
    NGAYTHANHTOAN DATETIME DEFAULT GETDATE(),
    PHUONGTHUC NVARCHAR(50),
    GHICHU NVARCHAR(MAX),
    MANV NVARCHAR(20),
    CONSTRAINT FK_THANHTOAN_HD FOREIGN KEY (SOHDXUAT) REFERENCES HOADONXUAT(SOHDXUAT),
    CONSTRAINT FK_THANHTOAN_NV FOREIGN KEY (MANV) REFERENCES NHANVIEN(MANV)
);
GO

