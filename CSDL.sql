-- Lưu ý: Nếu cột có ràng buộc DEFAULT GETDATE(), ta cần xóa ràng buộc trước (nhưng để đơn giản, ta chỉ đổi kiểu dữ liệu các cột không có Default)

-- Ngày sinh nhân viên
ALTER TABLE NHANVIEN ALTER COLUMN NGAYSINH NVARCHAR(50);

-- Hạn sử dụng lô hàng
ALTER TABLE LOHANG ALTER COLUMN NSX NVARCHAR(50);
ALTER TABLE LOHANG ALTER COLUMN HSD NVARCHAR(50);

-- Chuyển cột NGAYSINH về kiểu DATE chuẩn
